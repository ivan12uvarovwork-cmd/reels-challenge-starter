/**
 * Один стиль. Не пресет из списка - единственный объект, который ты
 * правишь под свой бренд.
 *
 * Если тебе, наоборот, нужен выбор из готовых пресетов (жёлтый, лайм,
 * минимал, glass, журнал) - смотри `ПРЕСЕТЫ_стилей.md` в этой же папке:
 * это более ранний, но рабочий подход с переключаемой палитрой. Файл
 * ниже - более поздний и более устойчивый подход: один узнаваемый язык
 * на весь канал вместо витрины вариантов, потому что зритель должен
 * узнавать ролик с первого кадра, а не гадать, какой сегодня пресет.
 *
 * Стиль держится на двух вещах, не на палитре:
 * 1. Субтитры проявляются группами по 1-2 слова синхронно с речью, не
 *    наплывом строки целиком и не побуквенной печатью (Subtitles.tsx).
 * 2. B-roll живёт в одной из трёх раскладок с анимированным переключением
 *    между ними (ui/BRollLayouts.tsx).
 * Цвет и шрифт здесь - просто чёрно-белая рамка для этой механики. Смело
 * меняй bg/ink/capBg/capInk/line на цвета своего бренда - логика выше от
 * этого не сломается.
 */
export type Style = {
  readonly bg: string;
  readonly ink: string;

  /** Плашка субтитров и текст в ней. */
  readonly capBg: string;
  readonly capInk: string;
  /** Скруглённая, не капсула во всю ширину строки. */
  readonly radius: number;

  /** Разделитель в сплит-экране, кромка кружка в PIP-раскладке. */
  readonly line: string;

  readonly fontText: string;
  readonly captionWeight: number;
  readonly scale: { readonly cap: number };
};

export const STYLE: Style = {
  bg: "#000000",
  ink: "#FFFFFF",

  capBg: "#000000",
  capInk: "#FFFFFF",
  radius: 22,

  line: "rgba(255,255,255,0.25)",

  // Unbounded - официальный Google Font с подтверждённой кириллицей (не
  // просто наличием кодпоинтов в cmap, а реальной проверкой рендером,
  // см. ГРАБЛИ.md п.8 - многие "поддерживающие кириллицу" шрифты рисуют
  // русские буквы через похожие по силуэту латинские, и это не видно,
  // пока не отрендеришь строку и не посмотришь на неё глазами).
  fontText: "'Unbounded', system-ui, Arial, sans-serif",
  captionWeight: 700,
  scale: { cap: 44 },
};
